import java.util.*;

class Codechef {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        int N = sc.nextInt();
        int G = sc.nextInt();

        if (N >= G) {
            System.out.println("Yes");
        } else {
            System.out.println("No");
        }
    }
}
